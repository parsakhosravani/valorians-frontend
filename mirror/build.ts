#!/usr/bin/env bun
/**
 * Builds the Telegram Serverless mirror of the game from the same source as the
 * Vercel app. Nothing outside mirror/ is changed:
 *
 *   1. backend  → mirror/tgcloud/lib/valorians.js
 *      src/server + every src/app/api route, bundled into one plain-JS module,
 *      with Node/Next-only imports swapped for the shims in mirror/shims/.
 *   2. Mini App → mirror/site/
 *      A copy of the app in mirror/.build/app with the API routes removed,
 *      `apiRequest` switched to Telegram.WebApp.Serverless.call, and Next's
 *      static export turned on.
 *
 * Usage (from the repo root, after `bun install`):
 *   bun mirror/build.ts            # both
 *   bun mirror/build.ts backend    # just the backend
 *   bun mirror/build.ts site       # just the Mini App
 *
 * Settings come from mirror/.env.mirror (see mirror/.env.mirror.example).
 */
import { $ } from "bun";
import fs from "fs";
import path from "path";
import crypto from "crypto";

const ROOT = path.resolve(import.meta.dir, "..");
const MIRROR = import.meta.dir;
const BUILD = path.join(MIRROR, ".build");
const what = process.argv[2] ?? "all";

// ─── Settings ────────────────────────────────────────────────────────────────

function loadEnv(): Record<string, string> {
  const file = path.join(MIRROR, ".env.mirror");
  const env: Record<string, string> = {};

  if (fs.existsSync(file)) {
    for (const line of fs.readFileSync(file, "utf8").split("\n")) {
      const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);

      if (m) env[m[1]] = m[2].replace(/^["']|["']$/g, "");
    }
  }
  if (!env.MIRROR_SECRET) {
    // Stands in for the bot token: secrets the game derives from the token
    // (admin link code, webhook secret) come from it, so it must stay private.
    env.MIRROR_SECRET = crypto.randomBytes(24).toString("hex");
    fs.appendFileSync(file, `\n# Generated by build.ts. Keep it private; changing it changes derived secrets.\nMIRROR_SECRET=${env.MIRROR_SECRET}\n`);
    console.log("Created MIRROR_SECRET in mirror/.env.mirror");
  }

  return env;
}

const env = loadEnv();

// ─── 1. Backend ──────────────────────────────────────────────────────────────

/** Routes that don't apply on Serverless: the platform owns the webhook, and the cron is entry.ts's job. */
const SKIP_ROUTES = new Set(["bot", "bot/setup", "cron/battles", "avatar/[id]"]);

function findRoutes(): string[] {
  const base = path.join(ROOT, "src/app/api");
  const out: string[] = [];
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      const p = path.join(dir, e.name);

      if (e.isDirectory()) walk(p);
      else if (e.name === "route.ts") out.push(path.relative(base, dir).split(path.sep).join("/"));
    }
  };

  walk(base);

  return out.filter((r) => !SKIP_ROUTES.has(r)).sort();
}

async function buildBackend() {
  fs.mkdirSync(BUILD, { recursive: true });
  const routes = findRoutes();
  const lines = routes.map((r, i) => `import * as r${i} from "@/app/api/${r}/route";`);

  lines.push(`export const routes = {\n${routes.map((r, i) => `  ${JSON.stringify(r)}: r${i},`).join("\n")}\n};`);
  fs.writeFileSync(path.join(BUILD, "routes.ts"), `// Generated by mirror/build.ts — do not edit.\n${lines.join("\n")}\n`);

  const shim = (f: string) => path.join(MIRROR, "shims", f);
  const serverEnv = {
    ...env,
    // The bot token is never needed on Serverless (the SDK's api is signed in);
    // the game only needs a non-empty, private value. See shims/runtime.ts.
    TELEGRAM_BOT_TOKEN: env.MIRROR_SECRET,
    NEXT_PUBLIC_TELEGRAM_BOT_TOKEN: "",
    // Any value: makes db.ts take the "hosted" path; shims/libsql.ts ignores it.
    TURSO_DATABASE_URL: "tgcloud",
    // A test mirror shouldn't message players about every release unless asked.
    RELEASE_ANNOUNCE: env.RELEASE_ANNOUNCE || "off",
  };
  delete (serverEnv as any).MIRROR_SECRET;

  const result = await Bun.build({
    entrypoints: [path.join(MIRROR, "entry.ts")],
    target: "browser",
    format: "esm",
    minify: false,
    external: ["sdk", "sdk/*"],
    banner: fs.readFileSync(shim("prelude.js"), "utf8").replace("__MIRROR_ENV__", JSON.stringify(serverEnv)),
    plugins: [
      {
        name: "mirror-shims",
        setup(build) {
          build.onResolve({ filter: /^server-only$/ }, () => ({ path: shim("empty.ts") }));
          build.onResolve({ filter: /^next\/server$/ }, () => ({ path: shim("next-server.ts") }));
          build.onResolve({ filter: /^@libsql\/client$/ }, () => ({ path: shim("libsql.ts") }));
          build.onResolve({ filter: /^(node:)?crypto$/ }, () => ({ path: shim("crypto.ts") }));
          build.onResolve({ filter: /^(node:)?(fs|path)$/ }, () => ({ path: shim("node-empty.ts") }));
          build.onResolve({ filter: /^(\.\/auth|@\/server\/auth)$/ }, () => ({ path: shim("auth.ts") }));
        },
      },
    ],
  });

  if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("Backend build failed");
  }
  const code = await result.outputs[0].text();
  const out = path.join(MIRROR, "tgcloud/lib/valorians.js");

  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(
    out,
    `// Generated by mirror/build.ts from src/ — do not edit. Rebuild with \`bun mirror/build.ts backend\`.\n${code}`
  );
  console.log(`Backend: ${routes.length} routes → mirror/tgcloud/lib/valorians.js (${Math.round(code.length / 1024)} KB)`);
}

// ─── 2. Mini App ─────────────────────────────────────────────────────────────

/** Replaces apiRequest in the copy so every call goes through the Serverless endpoint `api`. */
const SERVERLESS_API_REQUEST = `
/** Mirror build: every request goes to the Telegram Serverless endpoint \`api\` (see mirror/entry.ts). */
export async function apiRequest<T = PlayerView>(
  _auth: string,
  path: string,
  body?: object
): Promise<T> {
  const serverless = (window as any).Telegram?.WebApp?.Serverless;

  if (!serverless?.call) throw new ApiError("Open the game from Telegram", "unauthorized", 401);
  const [route, query = ""] = path.split("?");
  const out: { status: number; body: any } = await new Promise((resolve, reject) =>
    serverless.call(
      "api",
      { path: route, query, method: body ? "POST" : "GET", body: body ?? null },
      (err: any, result: any) =>
        err
          ? reject(new ApiError(err.message || "Network error", err.parameters?.code ?? "network", err.type === "ENDPOINT_ERROR" ? 400 : 500))
          : resolve(result)
    )
  );

  if (!out || out.status >= 400) {
    throw new ApiError(out?.body?.error ?? "Network error", out?.body?.code ?? "network", out?.status ?? 500);
  }

  return out.body as T;
}
`;

async function buildSite() {
  const app = path.join(BUILD, "app");

  fs.rmSync(app, { recursive: true, force: true });
  fs.mkdirSync(app, { recursive: true });
  for (const f of ["src", "public", "package.json", "tsconfig.json", "tailwind.config.ts", "postcss.config.mjs", "next.config.mjs", ".env"]) {
    const from = path.join(ROOT, f);

    if (fs.existsSync(from)) fs.cpSync(from, path.join(app, f), { recursive: true });
  }
  fs.symlinkSync(path.join(ROOT, "node_modules"), path.join(app, "node_modules"), "dir");

  // No server on a static host: drop the API routes (they live in the backend bundle now).
  fs.rmSync(path.join(app, "src/app/api"), { recursive: true, force: true });

  // Swap the transport. Everything else in api.ts (sign-in detection) stays.
  const apiFile = path.join(app, "src/lib/api.ts");
  const src = fs.readFileSync(apiFile, "utf8");
  const start = src.indexOf("export async function apiRequest");

  if (start === -1) throw new Error("src/lib/api.ts: apiRequest not found — update mirror/build.ts");
  fs.writeFileSync(apiFile, src.slice(0, start) + SERVERLESS_API_REQUEST);

  // Avatars: /api/avatar/<id> doesn't exist on the static host, so the <img>
  // fails and <Avatar> falls back to the game's default picture by itself.

  // Static export on top of the app's own config.
  fs.renameSync(path.join(app, "next.config.mjs"), path.join(app, "next.config.base.mjs"));
  fs.writeFileSync(
    path.join(app, "next.config.mjs"),
    `import base from "./next.config.base.mjs";\n\nexport default { ...base, output: "export", images: { unoptimized: true }, typedRoutes: false };\n`
  );

  const siteEnv = Object.fromEntries(Object.entries(env).filter(([k]) => k.startsWith("NEXT_PUBLIC_")));

  // Never ship the browser dev login in a deployed build.
  siteEnv.NEXT_PUBLIC_DEV_LOGIN = "";
  await $`bunx --bun next build`.cwd(app).env({ ...process.env, ...siteEnv, NEXT_TELEMETRY_DISABLED: "1" });

  const site = path.join(MIRROR, "site");

  fs.rmSync(site, { recursive: true, force: true });
  fs.cpSync(path.join(app, "out"), site, { recursive: true });
  // `/hall` and `/hall/` both work whichever way the host resolves pages.
  for (const f of fs.readdirSync(site)) {
    if (f.endsWith(".html") && f !== "index.html" && f !== "404.html") {
      const dir = path.join(site, f.slice(0, -5));

      fs.mkdirSync(dir, { recursive: true });
      fs.copyFileSync(path.join(site, f), path.join(dir, "index.html"));
    }
  }
  console.log("Mini App → mirror/site/");
}

if (what === "all" || what === "backend") await buildBackend();
if (what === "all" || what === "site") await buildSite();
