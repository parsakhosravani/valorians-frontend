let grid: Uint8Array | null = null;

/** What each tile of the world is: 0 sea, 1 land, 2 lake (row by row, NORTH.size a side). */
export function northGrid(): Uint8Array {
  if (grid) return grid;
  const B = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789-_";
  const g = new Uint8Array(NORTH.size * NORTH.size);
  let at = 0;

  for (let i = 0; i < RUNS.length; i += 2) {
    const hi = B.indexOf(RUNS[i]);
    const lo = B.indexOf(RUNS[i + 1]);
    const n = ((hi & 15) << 6) | lo;

    g.fill(hi >> 4, at, at + n);
    at += n;
  }
  grid = g;

  return g;
}

/** A tile's longitude and latitude (tile coordinates counted from the world's top-left corner). */
export const lonLat = (i: number, j: number) => ({
  lon: NORTH.lon + (i + 0.5 - NORTH.size / 2) / (NORTH.tilesPerDegree * 0.5),
  lat: NORTH.lat - (j + 0.5 - NORTH.size / 2) / NORTH.tilesPerDegree,
});
